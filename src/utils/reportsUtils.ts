// Generate insight text for doctor workload
export const generateDoctorInsight = (data: Record<string, number>): string => {
  const sorted = sortByValue(data);
  if (sorted.length === 0) return 'No doctor data available';

  const [topDoctor, count] = sorted[0];
  return `Most appointments: Dr. ${topDoctor} with ${count} patient${count !== 1 ? 's' : ''}`;
};
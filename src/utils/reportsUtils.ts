// Get area name from pincode
export const getAreaFromPincode = (pincode: string): string => {
  // Handle empty/null/undefined cases
  if (!pincode || pincode.trim() === '') {
    console.log('🔍 UNMAPPED: Empty pincode found');
    return 'No Pincode Provided';
  }

  // Clean and normalize pincode
  const cleanedPincode = pincode.toString().trim().replace(/[^0-9]/g, '');

  // Log unmapped pincodes for debugging
  if (!PINCODE_AREA_MAP[cleanedPincode]) {
    console.log(`🔍 UNMAPPED PINCODE: "${pincode}" (cleaned: "${cleanedPincode}")`);
  }

  return PINCODE_AREA_MAP[cleanedPincode] || 'Other Areas';
};

// Group patients by age ranges
export const groupByAgeRange = (age: number): string => {
  if (age <= 18) return '0-18 years';
  if (age <= 35) return '19-35 years';
  if (age <= 50) return '36-50 years';
  return '51+ years';
};

// Get day name from date
export const getDayName = (date: string): string => {
  const dayNames = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const day = new Date(date).getDay();
  return dayNames[day];
};

// Get month name from date
export const getMonthName = (date: string): string => {
  const monthNames = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
  ];
  const month = new Date(date).getMonth();
  return monthNames[month];
};

// Calculate percentage
export const calculatePercentage = (value: number, total: number): number => {
  return total === 0 ? 0 : Math.round((value / total) * 100);
};

// Sort object entries by value (descending)
export const sortByValue = (obj: Record<string, number>): [string, number][] => {
  return Object.entries(obj).sort(([, a], [, b]) => b - a);
};

// Get top N items from an object
export const getTopItems = (obj: Record<string, number>, n: number = 5): [string, number][] => {
  return sortByValue(obj).slice(0, n);
};

// Generate insight text for geographic data
export const generateGeographicInsight = (data: Record<string, number>): string => {
  const sorted = sortByValue(data);
  if (sorted.length === 0) return 'No patient data available';

  const [topArea, count] = sorted[0];
  return `Most patients from ${topArea}: ${count} patient${count !== 1 ? 's' : ''}`;
};

